const MESSAGES = { en: {}, sw: SW };

export function normalizeLocale(value) {
  return LOCALES.includes(value) ? value : DEFAULT_LOCALE;
}

// translate("sw", "Closes in {n} days", { n: 3 }) fills {name} placeholders.
export function translate(locale, text, values) {
  if (!text) return text;
  const message = MESSAGES[normalizeLocale(locale)][text] || text;
  if (!values) return message;
  return message.replace(/\{(\w+)\}/g, (match, key) => (key in values ? String(values[key]) : match));
}

